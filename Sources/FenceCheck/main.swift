import Foundation

// Usage: FenceCheck <stamp-output.swift> <source.swift>...
// Prints compiler-style errors and exits non-zero when a source imports a banned module.
let arguments = CommandLine.arguments.dropFirst()
guard let stampPath = arguments.first else {
    FileHandle.standardError.write(Data("usage: FenceCheck <stamp> <sources...>\n".utf8))
    exit(2)
}

var failed = false
for path in arguments.dropFirst() {
    guard let source = try? String(contentsOfFile: path, encoding: .utf8) else { continue }
    for violation in violations(in: source) {
        failed = true
        let message =
            "\(path):\(violation.line):1: error: HandyCore must not import \(violation.module); "
            + "platform code belongs in an adapter package (see docs/spec.md, the fence)\n"
        FileHandle.standardError.write(Data(message.utf8))
    }
}

if failed { exit(1) }
let stamp = "// Generated by FenceCheck: HandyCore imports are clean.\n"
FileManager.default.createFile(atPath: stampPath, contents: Data(stamp.utf8))
